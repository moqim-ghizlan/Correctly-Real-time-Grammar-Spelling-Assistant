"""Install only the isolated TestMode build; never use the real Startup or AppId."""
import argparse
import base64
import ctypes
from datetime import datetime, timezone
import json
import os
import platform
from pathlib import Path
import subprocess
import sys
import tempfile
import time
import winreg

from vendor_bundle import ROOT, digest
from engine_baseline import compare, capture

sys.path.insert(0, str(ROOT / "backend/src"))
from correctly_server.autostart import MARKER
from correctly_server.engine import Engine, State
from correctly_server.listener import listeners
from correctly_server.paths import Paths
from correctly_server.settings import Settings
from correctly_server.singleton import Singleton

TEST_KEY = r"Software\Microsoft\Windows\CurrentVersion\Uninstall\{19751EA6-761D-45B0-A263-3E79767863EB}_is1"


def registered():
    try:
        with winreg.OpenKey(winreg.HKEY_CURRENT_USER, TEST_KEY, 0, winreg.KEY_READ | winreg.KEY_WOW64_64KEY) as key:
            return {name: winreg.QueryValueEx(key, name)[0]
                    for name in ("DisplayName", "DisplayVersion", "InstallLocation")}
    except FileNotFoundError:
        return None


def release(setup):
    manifest = json.loads((setup.parent / "release-manifest.json").read_text(encoding="utf-8-sig"))
    if manifest.get("test_mode") is not True or digest(setup) != manifest["setup_sha256"]:
        raise ValueError("Only a verified TestMode installer may be run by this script")
    return manifest


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--installer", type=Path, required=True)
    parser.add_argument("--upgrade-installer", type=Path)
    parser.add_argument("--report-dir", type=Path, required=True)
    args = parser.parse_args()
    setup = args.installer.resolve(strict=True)
    manifest = release(setup)
    upgrade = args.upgrade_installer.resolve(strict=True) if args.upgrade_installer else None
    upgrade_manifest = release(upgrade) if upgrade else None
    if registered() is not None:
        raise ValueError("Isolated test AppId already installed; inspect it before retrying")
    output = args.report_dir.resolve()
    output.mkdir(parents=True, exist_ok=True)
    install = Path(tempfile.mkdtemp(prefix="Correctly essai été ")) / "Correctly"
    startup = install / "test-startup/Correctly.lnk"
    log_number = 0
    report = {"executed_at": datetime.now(timezone.utc).isoformat(), "test_mode": True,
              "windows": platform.platform(), "elevated": bool(ctypes.windll.shell32.IsUserAnAdmin()),
              "install_path": str(install), "passed": [], "not_tested": [], "ok": False}
    environment = dict(os.environ)
    environment["PATH"] = str(Path(os.environ["SystemRoot"]) / "System32")
    environment["JAVA_HOME"] = "C:/missing-java"
    environment["JAVA_TOOL_OPTIONS"] = "invalid inherited JVM option"
    for key in ("PYTHONPATH", "PYTHONHOME"):
        environment.pop(key, None)
    original_listener = [row for row in listeners() if row[1] == 8081]
    original_startup = Path(os.environ["APPDATA"]) / "Microsoft/Windows/Start Menu/Programs/Startup"
    original_links = {str(file): digest(file) for file in original_startup.glob("*.lnk")}

    def run(executable, arguments, timeout=240):
        return subprocess.run([str(executable), *arguments], env=environment, cwd=str(output),
                              creationflags=subprocess.CREATE_NO_WINDOW, timeout=timeout,
                              stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL).returncode

    def install_setup(tasks=None, executable=setup):
        nonlocal log_number
        log_number += 1
        parameters = ["/VERYSILENT", "/SUPPRESSMSGBOXES", "/NORESTART", "/SP-",
                      "/DIR=" + str(install), "/LOG=" + str(output / f"setup-{log_number}.log")]
        if tasks is not None:
            parameters.append("/TASKS=" + tasks)
        print(f"Installer scenario {log_number}: tasks={tasks!r}", flush=True)
        code = run(executable, parameters)
        print(f"Installer scenario {log_number}: exit={code}", flush=True)
        return code

    def link_info():
        # Windows COM, with only paths generated by this test; no shell interpolation.
        command = "$s=(New-Object -ComObject WScript.Shell).CreateShortcut($env:CORRECTLY_TEST_LINK);@{target=[Convert]::ToBase64String([Text.Encoding]::Unicode.GetBytes($s.TargetPath));description=$s.Description}|ConvertTo-Json"
        link_environment = dict(environment, CORRECTLY_TEST_LINK=str(startup))
        data = subprocess.check_output([str(Path(os.environ["SystemRoot"]) / "System32/WindowsPowerShell/v1.0/powershell.exe"),
                                        "-NoProfile", "-NonInteractive", "-Command", command],
                                       env=link_environment, creationflags=subprocess.CREATE_NO_WINDOW, timeout=15)
        value = json.loads(data.decode("utf-8-sig"))
        value["target"] = base64.b64decode(value["target"]).decode("utf-16-le")
        return value

    engine = None
    try:
        assert install_setup() == 0
        assert registered()["DisplayVersion"] == manifest["version"]
        assert Path(registered()["InstallLocation"]).resolve() == install.resolve()
        files = json.loads((setup.parent / "bundle-files.json").read_text(encoding="utf-8"))["files"]
        for name, expected in files.items():
            assert digest(install / name) == expected, name
        report["passed"].append(f"initial per-user installation: all {len(files)} bundle checksums, registry, uninstaller")
        if not report["elevated"]:
            report["passed"].append("setup ran under a non-elevated Windows token")
        assert (install / "unins000.exe").is_file()
        assert (install / "test-start-menu/Correctly.lnk").is_file()
        assert startup.is_file()
        link = link_info()
        # COM's PowerShell output uses the Windows code page on legacy hosts.
        assert link["description"] == MARKER
        assert os.path.normcase(link["target"]) == os.path.normcase(str(install / "CorrectlyServer.exe"))
        report["passed"].append("default checked autostart creates a COM shortcut with the tray ownership marker")
        personal = install / "personal-note.txt"
        personal.write_text("user file must survive upgrade and uninstall", encoding="utf-8")

        assert install_setup(tasks="") == 0 and not startup.exists()
        assert install_setup() == 0 and not startup.exists()
        assert install_setup(tasks="autostart") == 0 and startup.is_file()
        report["passed"].append("reinstall: disable, preserve disabled selection, re-enable without duplicate shortcuts")
        if upgrade:
            assert install_setup(executable=upgrade) == 0
            assert registered()["DisplayVersion"] == upgrade_manifest["version"] and startup.is_file()
            assert personal.read_text(encoding="utf-8") == "user file must survive upgrade and uninstall"
            report["passed"].append("version upgrade preserves user file, installation path and enabled autostart")
        else:
            report["not_tested"].append("different-version upgrade: no upgrade installer supplied")

        exe = install / "CorrectlyServer.exe"
        smoke = output / "installed-smoke.json"
        first = subprocess.Popen([str(exe), "--smoke-test", str(smoke), "--port", "18084"],
                                 env=environment, cwd=str(output), creationflags=subprocess.CREATE_NO_WINDOW,
                                 stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        test_mutex = Singleton(r"Local\CorrectlyServer.V3.Smoke.18084")
        try:
            deadline = time.monotonic() + 15
            while test_mutex.acquire():
                test_mutex.close()
                if time.monotonic() > deadline:
                    raise AssertionError("Installed EXE did not acquire its smoke mutex")
                time.sleep(.05)
            duplicate = output / "installed-duplicate.json"
            assert run(exe, ["--smoke-test", str(duplicate), "--port", "18084"]) == 2
            assert json.loads(duplicate.read_text(encoding="utf-8"))["error"] == "already_running"
            assert first.wait(timeout=150) == 0
        finally:
            test_mutex.close()
            if first.poll() is None:
                first.wait(timeout=150)  # Never kill the controller and orphan its child.
        smoke_result = json.loads(smoke.read_text(encoding="utf-8"))
        assert smoke_result["ok"] and smoke_result["stopped"]
        report["passed"].append("installed EXE in Unicode/space path: private FR/EN with no Java/Python/Node on PATH")
        report["passed"].append("duplicate installed smoke EXE refuses a second JVM on the test port")
        assert run(exe, ["--shutdown"]) == 0
        report["passed"].append("shutdown control excludes active portable Correctly at a different executable path")

        engine = Engine(Paths(install), Settings(port=18085))
        engine.start()
        assert engine.state == State.RUNNING
        compare(json.loads((ROOT / "docs/baseline/v2-responses.json").read_text(encoding="utf-8")), capture(18085))
        assert engine.stop()
        report["passed"].append("installed complete engine: strict 11-case FR/EN/Auto/Unicode equivalence")

        # A foreign shortcut must block a reinstall, never be silently replaced.
        saved = startup.read_bytes()
        startup.write_bytes(b"unmanaged test shortcut")
        assert install_setup() != 0
        assert startup.read_bytes() == b"unmanaged test shortcut"
        assert digest(exe) == files["CorrectlyServer.exe"]
        startup.write_bytes(saved)
        report["passed"].append("foreign shortcut blocks installation and remains unchanged")

        assert run(install / "unins000.exe", ["/VERYSILENT", "/SUPPRESSMSGBOXES", "/NORESTART",
                                              "/LOG=" + str(output / "uninstall.log")]) == 0
        assert registered() is None and not exe.exists() and not startup.exists()
        assert personal.is_file()
        report["passed"].append("uninstall removes program, HKCU registration and managed autostart; preserves user file")
        assert install_setup(tasks="autostart") == 0
        startup.write_bytes(b"foreign shortcut must survive uninstall")
        assert run(install / "unins000.exe", ["/VERYSILENT", "/SUPPRESSMSGBOXES", "/NORESTART",
                                              "/LOG=" + str(output / "uninstall-foreign-shortcut.log")]) == 0
        assert registered() is None and not exe.exists()
        assert startup.read_bytes() == b"foreign shortcut must survive uninstall" and personal.is_file()
        report["passed"].append("uninstall preserves a replaced foreign startup shortcut")
        assert original_listener == [row for row in listeners() if row[1] == 8081]
        assert original_links == {str(file): digest(file) for file in original_startup.glob("*.lnk")}
        report["passed"].append("real Startup links and existing production listener on 8081 unchanged")
        report["not_tested"].extend(["clean Windows without installed development runtimes",
                                   "Windows sign-out/reboot and default-directory production installation",
                                   "live installed tray while another Correctly V3 owns the session singleton",
                                   "Chrome/Brave authenticated sites and antivirus/SmartScreen interactive behavior"])
        report["ok"] = True
    except Exception as error:
        report["failure"] = {"type": type(error).__name__, "detail": str(error)}
        raise
    finally:
        if engine:
            engine.stop()
        # Only this isolated uninstaller may clean this test's registered program.
        if registered() is not None and (install / "unins000.exe").is_file():
            report["cleanup_exit"] = run(install / "unins000.exe", ["/VERYSILENT", "/SUPPRESSMSGBOXES", "/NORESTART"])
        (output / "installer-validation.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
